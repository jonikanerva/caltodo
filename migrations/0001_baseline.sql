-- The schema of the Node server: the result of its four Drizzle migrations
-- (`0000_gifted_zemo` to `0003_action_tokens`). ADR 0003 records the policy.
--
-- Every statement is idempotent, so this migration changes nothing on a
-- database that the Drizzle migrator already set up (production), and it
-- builds the same schema on an empty database. The Drizzle ledger
-- (`drizzle.__drizzle_migrations`) stays untouched, so a revert to the Node
-- server finds its migrations applied.
--
-- The inline UNIQUE and REFERENCES clauses keep the constraint names that
-- PostgreSQL gave them under Drizzle. `user_sessions` is the session table of
-- the Node server; the Rust server does not use it, but a revert needs it.
-- Do not edit this file after a release: SQLx checks its checksum.

CREATE TABLE IF NOT EXISTS "user_sessions" (
  "sid" varchar PRIMARY KEY NOT NULL,
  "sess" json NOT NULL,
  "expire" timestamp (6) NOT NULL
);

CREATE TABLE IF NOT EXISTS "user_settings" (
  "id" varchar PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "user_id" varchar NOT NULL,
  "calendar_id" text,
  "work_start_hour" integer DEFAULT 9 NOT NULL,
  "work_end_hour" integer DEFAULT 17 NOT NULL,
  "timezone" text DEFAULT 'America/New_York' NOT NULL,
  "default_duration" integer DEFAULT 60 NOT NULL,
  "event_color" text DEFAULT '1' NOT NULL,
  CONSTRAINT "user_settings_user_id_unique" UNIQUE("user_id")
);

CREATE TABLE IF NOT EXISTS "users" (
  "id" varchar PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "google_id" text NOT NULL,
  "email" text NOT NULL,
  "display_name" text NOT NULL,
  "access_token" text,
  "refresh_token" text,
  CONSTRAINT "users_google_id_unique" UNIQUE("google_id")
);

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'user_settings_user_id_users_id_fk'
  ) THEN
    ALTER TABLE "user_settings"
      ADD CONSTRAINT "user_settings_user_id_users_id_fk"
      FOREIGN KEY ("user_id") REFERENCES "public"."users"("id")
      ON DELETE no action ON UPDATE no action;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS "action_tokens" (
  "id" varchar PRIMARY KEY DEFAULT gen_random_uuid(),
  "token_hash" text NOT NULL UNIQUE,
  "user_id" varchar NOT NULL REFERENCES "users"("id"),
  "event_id" text NOT NULL,
  "calendar_id" text NOT NULL,
  "expires_at" timestamp(6) NOT NULL,
  "used_at" timestamp(6),
  "created_at" timestamp(6) NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS "action_tokens_user_id_idx" ON "action_tokens" ("user_id");
CREATE INDEX IF NOT EXISTS "action_tokens_event_id_idx" ON "action_tokens" ("event_id");
CREATE INDEX IF NOT EXISTS "action_tokens_calendar_id_idx" ON "action_tokens" ("calendar_id");
CREATE INDEX IF NOT EXISTS "action_tokens_expires_at_idx" ON "action_tokens" ("expires_at");
